def _validate_strict_context_match(original_uid: str, candidate_uid: str) -> bool:
    """100% STRICT context validation - ensures UIDs are from the same functional context."""
    import re
    
    # Extract context indicators (page names, flows)
    def extract_context(uid):
        contexts = set()
        text = uid.lower()
        
        # Page/flow contexts
        page_patterns = r'(checkout|login|signup|profile|payment|billing|shipping|cart|search|product|landing|auth|wallet)'
        contexts.update(re.findall(page_patterns, text))
        
        # Action contexts
        action_patterns = r'(click|enter|select|verify|submit|navigate)'
        contexts.update(re.findall(action_patterns, text))
        
        return contexts
    
    orig_contexts = extract_context(original_uid)
    cand_contexts = extract_context(candidate_uid)
    
    # Check if contexts exist and overlap
    if orig_contexts and cand_contexts:
        shared_contexts = orig_contexts & cand_contexts
        return len(shared_contexts) > 0
    
    # If no specific contexts found, fall back to token-based context matching
    # This handles simple field names like "email_address_field" vs "email_address_input"
    orig_tokens = set(original_uid.lower().split('_'))
    cand_tokens = set(candidate_uid.lower().split('_'))
    
    if not orig_tokens or not cand_tokens:
        return False
        
    shared_tokens = orig_tokens & cand_tokens
    
    # Calculate context overlap ratios
    orig_ratio = len(shared_tokens) / len(orig_tokens) if orig_tokens else 0.0
    cand_ratio = len(shared_tokens) / len(cand_tokens) if cand_tokens else 0.0
    
    # ADJUSTED: Use 50% threshold for simple field names instead of 60%
    min_threshold = 0.50
    return orig_ratio >= min_threshold and cand_ratio >= min_threshold


def _is_form_field_match(original: str, candidate: str) -> bool:
    """100% STRICT form field matching - zero tolerance for field type conflicts."""
    
    # STRICT CHECK: Extract semantic types
    orig_type = _extract_field_semantic_type(original)
    cand_type = _extract_field_semantic_type(candidate)
    
    # If both have types, they MUST match exactly
    if orig_type and cand_type:
        if orig_type != cand_type:
            return False  # Hard rejection
        return True  # Exact match
    
    # If only one has a type, check for conflicting patterns
    if orig_type or cand_type:
        # One is typed, other is not - be very cautious
        return _has_shared_form_tokens(original, candidate) and _tokens_similarity(original, candidate) > 0.8
    
    # Neither has clear semantic type - use token-based strict matching
    return _has_shared_form_tokens(original, candidate)


def _tokens_similarity(original: str, candidate: str) -> float:
    """Calculate strict token-based similarity."""
    import re
    
    def extract_tokens(text):
        tokens = re.findall(r'\b\w{3,}\b', text.lower())
        stop_words = {'user', 'then', 'enters', 'clicks', 'selects', 'the', 'and', 'with', 'for', 'as', 'chewy', 'web', 'storefront'}
        return set(token for token in tokens if token not in stop_words)
    
    orig_tokens = extract_tokens(original)
    cand_tokens = extract_tokens(candidate)
    
    if not orig_tokens or not cand_tokens:
        return 0.0
    
    shared = orig_tokens & cand_tokens
    total = orig_tokens | cand_tokens
    
    return len(shared) / len(total) if total else 0.0



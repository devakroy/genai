def push_steps_df(
    df: pd.DataFrame,
    *,
    table: str = "t_locators",
    schema: Optional[str] = None,
    db: Optional[Dict[str, str]] = None,
    significant_cols: Optional[List[str]] = None,
    key_col: Optional[str] = None,   # kept for backward-compat; ignored
    only_js_crawl: bool = False,     # push only rows produced by JS crawl if True
    unique_id_constraint: str = "unique_id_pkey",  # DB constraint name for unique_id primary key
    **_: dict,
) -> int:
    """
    Persist a steps DataFrame into Postgres while enforcing:
      - No NULL/blank unique_id inserted
      - No duplicates by unique_id: update when significant fields changed; insert when brand new
      - Skip non-action rows: 'Navigate'
      - Skip duplicate playwrightLocator rows in-batch (but allow different unique_ids with same locator)
      - ON CONFLICT (unique_id) DO UPDATE to properly handle locator updates per unique_id
      - Optionally push only rows generated by JS crawl (only_js_crawl=True)
    """
    if df is None or df.empty:
        return 0

    sig_cols = significant_cols or SIGNIFICANT_COLS_DEFAULT

    # connection config
    cfg = {
        "host": PLATFORM_CONFIG.get("PGHOST", PGHOST),
        "port": PLATFORM_CONFIG.get("PGPORT", PGPORT),
        "dbname": PLATFORM_CONFIG.get("PGDATABASE", PGDATABASE),
        "user": PLATFORM_CONFIG.get("PGUSER", PGUSER),
        "password": PLATFORM_CONFIG.get("PGPASSWORD", PGPASSWORD),
        "sslmode": PLATFORM_CONFIG.get("PGSSLMODE", PGSSLMODE),
        "schema": schema or PLATFORM_CONFIG.get("PGSCHEMA", PGSCHEMA),
    }
    if db:
        cfg.update(db)

    local_url = (
        f"postgresql+psycopg2://{cfg['user']}:{cfg['password']}"
        f"@{cfg['host']}:{cfg['port']}/{cfg['dbname']}?sslmode={cfg['sslmode']}"
    )
    eng: Engine = _get_engine(local_url)

    # reflect table
    meta = MetaData(schema=cfg["schema"])
    meta.reflect(bind=eng, only=[table])
    tbl = meta.tables[f"{cfg['schema']}.{table}"]

    # keep only existing columns
    db_cols = [c.name for c in tbl.columns]
    cols = [c for c in db_cols if c in df.columns]
    if not cols:
        return 0

    df_to_push = df[cols].copy()

    # ✅ Filter out dynamic content that shouldn't be stored
    if "original_bdd_step" in df_to_push.columns:
        def _contains_dynamic_content_db(step_text: str) -> bool:
            """
            Enhanced check for dynamic content that shouldn't be cached.
            This function detects various patterns of dynamic content to prevent
            caching locators that won't be reusable due to changing values.
            """
            if not step_text:
                return False
            
            step_lower = str(step_text).lower()
            
            # Skip if step explicitly contains 'dynamic' keyword
            if "dynamic" in step_lower:
                return True
            
            # Check for common dynamic content patterns
            dynamic_patterns = [
                # Email addresses
                r'\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Z|a-z]{2,}\b',
                # Placeholder patterns like {variableName} or {{variableName}}
                r'\{\{?[^}]+\}\}?',
                # Phone numbers
                r'\b\(?[\d]{3}\)?[-.\s]?[\d]{3}[-.\s]?[\d]{4}\b',
                # Timestamps and dates
                r'\b\d{4}[-/]\d{2}[-/]\d{2}(?:[T\s]\d{2}:\d{2}:\d{2}(?:\.\d{3})?(?:Z|[+-]\d{2}:\d{2})?)?\b',
                # UUIDs
                r'\b[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}\b',
                # Long numeric IDs (6+ digits)
                r'\b\d{6,}\b',
                # Credit card numbers
                r'\b(?:\d{4}[-\s]?){3}\d{4}\b'
            ]
            
            # Check if any pattern matches
            for pattern in dynamic_patterns:
                if re.search(pattern, step_text, re.IGNORECASE):
                    return True
            
            # Additional heuristic checks
            # Check for common dynamic keywords in step text
            dynamic_keywords = [
                'random', 'generate', 'timestamp', 'uuid', 'guid', 
                'current', 'now', 'today', 'temp', 'temporary'
            ]
            
            for keyword in dynamic_keywords:
                if keyword in step_lower:
                    return True
            
            # Specific check for resolved placeholder patterns
            # These patterns indicate that a placeholder was resolved to a dynamic value
            resolved_placeholder_patterns = [
                # Clicks on pure numeric values (likely resolved userIds, orderIds)
                r'clicks on "\d+"',
                r'click on "\d+"',
                # Enters field with numeric value (likely resolved IDs)
                r'enters "[^"]*" as "\d+"',
                r'enter "[^"]*" as "\d+"',
                # Navigate to URLs with long numeric IDs
                r'navigate.*\/\d{6,}',
                # Select options with numeric IDs
                r'select.*"\d{6,}"'
            ]
            
            for pattern in resolved_placeholder_patterns:
                if re.search(pattern, step_text, re.IGNORECASE):
                    return True

            return False
        
        # Filter out dynamic content
        original_count = len(df_to_push)
        dynamic_mask = df_to_push["original_bdd_step"].apply(_contains_dynamic_content_db)
        
        if dynamic_mask.any():
            dynamic_steps = df_to_push[dynamic_mask]["original_bdd_step"].head(3).tolist()
            logger.info(f"🚫 DB-FILTER: DYNAMIC CONTENT | {dynamic_mask.sum()} steps filtered | Examples: {[s[:50] + '...' if len(s) > 50 else s for s in dynamic_steps]}")
        
        df_to_push = df_to_push[~dynamic_mask]
        
        if len(df_to_push) < original_count:
            logger.info(f"🚫 DB-FILTER: REMOVED DYNAMIC | {original_count - len(df_to_push)} dynamic steps | {len(df_to_push)} remaining")

    # --- optional: only JS-crawl rows ---
    if only_js_crawl and "generated_by" in df_to_push.columns:
        df_to_push = df_to_push[df_to_push["generated_by"].astype(str).str.lower().eq("js_crawl")]

    # drop Navigate steps
    if "action" in df_to_push.columns:
        nav_count_before = len(df_to_push)
        df_to_push = df_to_push[
            df_to_push["action"].apply(lambda x: (x or "").strip().lower() != "navigate")
        ]
        if len(df_to_push) < nav_count_before:
            logger.debug(f"🚫 DB-FILTER: NAVIGATION | {nav_count_before - len(df_to_push)} navigate steps removed")

    # ✅ normalize NaNs -> None BEFORE unique_id filtering
    df_to_push = df_to_push.where(pd.notnull(df_to_push), None)

    # ✅ require unique_id and drop null/blank/"nan" strings
    if "unique_id" not in df_to_push.columns:
        return 0
    df_to_push = df_to_push[
        (df_to_push["unique_id"].apply(lambda v: v is not None))
        & (df_to_push["unique_id"].astype(str).str.strip() != "")
        & (df_to_push["unique_id"].astype(str).str.lower() != "nan")
    ]
    if df_to_push.empty:
        return 0

    # in-batch dedupe on playwrightLocator
    if "playwrightLocator" in df_to_push.columns:
        df_to_push = df_to_push.dropna(subset=["playwrightLocator"])
        df_to_push = df_to_push.drop_duplicates(subset=["playwrightLocator"])

    # prepare latest snapshot by unique_id (safe as strings)
    uids = sorted({
        str(v).strip()
        for v in df_to_push["unique_id"]
        if v is not None and str(v).strip() != ""
    })
    latest_by_uid: Dict[str, Dict[str, object]] = {}

    with eng.begin() as conn:
        if uids:
            subq = (
                select(
                    tbl.c.unique_id,
                    func.max(tbl.c.id).label("max_id")
                )
                .where(tbl.c.unique_id.in_(uids))
                .group_by(tbl.c.unique_id)
                .subquery()
            )
            latest_rows = conn.execute(
                select(tbl).join(
                    subq, and_(tbl.c.unique_id == subq.c.unique_id, tbl.c.id == subq.c.max_id)
                )
            ).mappings().all()
            for row in latest_rows:
                latest_by_uid[row["unique_id"]] = dict(row)

    inserts: List[Dict[str, object]] = []
    updates: List[Dict[str, object]] = []
    intelligent_updates: List[Dict[str, object]] = []  # For semantic matches
    comparable_cols = [c for c in sig_cols if c in db_cols and c in df_to_push.columns]

    # 🧠 Enhanced decision logic: exact match -> intelligent semantic match -> insert
    for _, rec in df_to_push.iterrows():
        rec_d = rec.to_dict()
        uid = str(rec_d["unique_id"]).strip()
        latest = latest_by_uid.get(uid)

        if latest is None:
            # No exact UID match found - try intelligent semantic matching
            semantic_match = _find_bulk_semantic_match(uid, latest_by_uid, rec_d)
            
            if semantic_match:
                # Found semantically similar record to update
                match_uid, match_record = semantic_match
                logger.debug(f"🧠 BULK-SEMANTIC MATCH | Input: {uid[:50]}... | Found: {match_uid[:50]}...")
                
                # Check if significant fields changed
                changed = any(
                    (match_record.get(c) or None) != (rec_d.get(c) or None)
                    for c in comparable_cols
                )
                if changed:
                    rec_d["id"] = match_record["id"]
                    rec_d["_semantic_match_uid"] = match_uid  # Track for logging
                    intelligent_updates.append(rec_d)
                # If no changes, skip this record (semantic duplicate)
            else:
                # No semantic match either - insert as new
                inserts.append(rec_d)
            continue

        # Exact UID match found - check for changes or incomplete records
        
        # 🔧 ENHANCED: Check if existing record is "incomplete" (only has locator data)
        # This happens when individual locator updates created records with only playwrightLocator filled
        existing_non_empty_cols = [
            c for c in comparable_cols 
            if latest.get(c) is not None and str(latest.get(c, '')).strip() != ''
        ]
        
        # If existing record has very few columns filled, it's likely incomplete
        is_incomplete_record = len(existing_non_empty_cols) <= 2  # Only playwrightLocator + maybe unique_id
        
        if is_incomplete_record:
            logger.info(f"💾 DB-BATCH: INCOMPLETE RECORD DETECTED 🔄 | {uid[:50]}... | Existing has only {len(existing_non_empty_cols)} columns filled, updating with complete data")
            rec_d["id"] = latest["id"]
            updates.append(rec_d)
        else:
            # Normal change detection for complete records
            changed = any(
                (latest.get(c) or None) != (rec_d.get(c) or None)
                for c in comparable_cols
            )
            if changed:
                logger.debug(f"💾 DB-BATCH: CONTENT CHANGE DETECTED 🔄 | {uid[:50]}... | Updating with changed data")
                rec_d["id"] = latest["id"]
                updates.append(rec_d)

    # Log operation summary
    total_updates = len(updates) + len(intelligent_updates)
    logger.info(f"💾 DB-BATCH: PREPARE | {len(inserts)} new inserts | {total_updates} updates planned ({len(updates)} exact + {len(intelligent_updates)} semantic)")
    
    if inserts:
        insert_uids = [str(rec.get('unique_id', 'unknown'))[:50] for rec in inserts[:3]]  # Show first 3
        more_msg = f" (+{len(inserts)-3} more)" if len(inserts) > 3 else ""
        logger.info(f"💾 DB-BATCH: NEW UNIQUE_IDS ✨ | {insert_uids}{more_msg}")
    
    if updates:
        update_uids = [str(rec.get('unique_id', 'unknown'))[:50] for rec in updates[:3]]  # Show first 3
        more_msg = f" (+{len(updates)-3} more)" if len(updates) > 3 else ""
        logger.info(f"💾 DB-BATCH: EXACT UPDATE UNIQUE_IDS 🔄 | {update_uids}{more_msg}")
    
    if intelligent_updates:
        smart_update_examples = []
        for rec in intelligent_updates[:3]:
            input_uid = str(rec.get('unique_id', 'unknown'))[:30]
            match_uid = str(rec.get('_semantic_match_uid', 'unknown'))[:30]
            smart_update_examples.append(f"{input_uid}→{match_uid}")
        more_msg = f" (+{len(intelligent_updates)-3} more)" if len(intelligent_updates) > 3 else ""
        logger.info(f"💾 DB-BATCH: INTELLIGENT UPDATE MATCHES 🧠 | {smart_update_examples}{more_msg}")

    written = 0
    with eng.begin() as conn:
        # Process all updates (exact + intelligent)
        all_updates = updates + intelligent_updates
        if all_updates:
            logger.info(f"💾 DB-BATCH: UPDATING 🔄 | {len(all_updates)} total records ({len(updates)} exact + {len(intelligent_updates)} semantic)")
            set_cols = [c for c in db_cols if c != "id"]
            upd_stmt = (
                tbl.update()
                .where(tbl.c.id == bindparam("b_id"))
                .values(**{c: bindparam(f"b_{c}") for c in set_cols})
            )
            upd_params = []
            for rec in all_updates:
                params = {"b_id": rec["id"]}
                for c in set_cols:
                    # Skip internal tracking fields
                    if c.startswith('_semantic_'):
                        continue
                    params[f"b_{c}"] = rec.get(c, None)
                upd_params.append(params)
            conn.execute(upd_stmt, upd_params)
            written += len(all_updates)
            logger.info(f"💾 DB-BATCH: UPDATED ✅ | {len(all_updates)} records successfully updated")

        # inserts with ON CONFLICT (unique_id) DO UPDATE for legitimate updates
        if inserts:
            logger.info(f"💾 DB-BATCH: INSERTING ✨ | {len(inserts)} new records with all details")
            pk_names = {c.name for c in tbl.primary_key.columns}
            insert_cols = [c for c in db_cols if c not in pk_names]

            insert_df = pd.DataFrame(inserts)
            for c in insert_cols:
                if c not in insert_df.columns:
                    insert_df[c] = None
            insert_df = insert_df[insert_cols].where(pd.notnull(insert_df), None)

            logger.debug(f"💾 DB-BATCH: INSERT COLUMNS | {len(insert_cols)} columns: {insert_cols[:10]}{'...' if len(insert_cols) > 10 else ''}")

            fqtn = tbl.fullname  # e.g. public.t_locators
            cols_sql = ",".join(f'"{c}"' for c in insert_cols)
            sql = (
                f'INSERT INTO {fqtn} ({cols_sql}) VALUES %s '
                f'ON CONFLICT (unique_id) DO UPDATE SET '
                f'"playwrightLocator" = EXCLUDED."playwrightLocator"'
            )

            cur = conn.connection.cursor()
            execute_values(
                cur,
                sql,
                [tuple(row[c] for c in insert_df.columns) for _, row in insert_df.iterrows()],
                page_size=1000,
            )
            written += len(inserts)
            logger.info(f"💾 DB-BATCH: INSERTED ✅ | {len(inserts)} new records (conflicts auto-skipped)")

    logger.info(f"💾 DB-BATCH: COMPLETE 🎯 | {written} total records processed | {len(inserts)} inserted + {len(updates)} updated")
    return written



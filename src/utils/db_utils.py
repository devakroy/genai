def update_locator_validity(unique_id: str, updated_locator: str, valid: bool = False, table: str = "t_locators") -> bool:
    """
    Insert or update a locator in the database using UPSERT logic.
    Creates new record if unique_id doesn't exist, updates existing record if it does.
    
    Args:
        unique_id: The exact unique identifier for the locator
        updated_locator: The updated locator string
        valid: Whether the locator is valid (False to mark as invalid)
        table: Database table name
    
    Returns:
        bool: True if upsert was successful
    """
    if not unique_id:
        logger.error(f"🗄️ DB-UPDATE: ERROR ❌ | Empty unique_id provided")
        return False

    # Handle locator validity marking
    if not valid and "/* INVALID_LOCATOR */" not in updated_locator:
        # Mark as invalid by adding prefix
        updated_locator = f"/* INVALID_LOCATOR */ {updated_locator}"
    elif valid and "/* INVALID_LOCATOR */" in updated_locator:
        # Remove invalid marker when updating with valid locator
        updated_locator = updated_locator.replace("/* INVALID_LOCATOR */ ", "").replace("/* INVALID_LOCATOR */", "")
        logger.debug(f"🔄 DB-UPDATE: REMOVE INVALID MARKER | {unique_id} | Cleaned locator for valid update")

    def _do_upsert() -> bool:
        with engine.begin() as conn:
            # Use UPSERT logic - INSERT if not exists, UPDATE if exists
            result = conn.execute(
                text(f"""
                    INSERT INTO {PGSCHEMA}.{table} (unique_id, "playwrightLocator")
                    VALUES (:u_exact, :new_locator)
                    ON CONFLICT (unique_id) 
                    DO UPDATE SET "playwrightLocator" = EXCLUDED."playwrightLocator"
                """),
                {"new_locator": updated_locator, "u_exact": unique_id}
            )
            
            rows_affected = result.rowcount
            if rows_affected > 0:
                logger.info(f"🗄️ DB-UPSERT: SUCCESS ✅ | {unique_id} | Inserted/Updated locator")
                return True
            else:
                logger.warning(f"🗄️ DB-UPSERT: NO CHANGE ❌ | {unique_id} | No rows affected")
                return False

    try:
        return _do_upsert()
    except OperationalError as e:
        logger.warning(f"❌ DB-UPSERT: CONNECTION ERROR | {e}")
        return False
    except DatabaseError as e:
        logger.warning(f"❌ DB-UPSERT: DATABASE ERROR | {e}")
        return False


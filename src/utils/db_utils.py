_ENGINE_CACHE: Dict[str, Engine] = {}

def _psql_insert_skip_duplicates(table, conn, keys, data_iter):
    """
    Pandas to_sql 'method' callback:
    bulk insert with ON CONFLICT (unique_id) DO UPDATE for locator updates.
    """
    rows = list(data_iter)
    if not rows:
        return

    fqtn = table.fullname  # e.g., 'public.t_locators'
    cols = ','.join(f'"{k}"' for k in keys)
    sql = (
        f'INSERT INTO {fqtn} ({cols}) VALUES %s '
        f'ON CONFLICT (unique_id) DO UPDATE SET "playwrightLocator" = EXCLUDED."playwrightLocator"'
    )

    cur = conn.connection.cursor()  # psycopg2 cursor under SQLAlchemy
    execute_values(cur, sql, rows, page_size=1000)

def _build_engine(url: str) -> Engine:
    return create_engine(
        url,
        pool_pre_ping=True,
        pool_size=int(PLATFORM_CONFIG.get("DB_POOL_SIZE", 5)),
        max_overflow=int(PLATFORM_CONFIG.get("DB_MAX_OVERFLOW", 0)),
        pool_recycle=int(PLATFORM_CONFIG.get("DB_POOL_RECYCLE", 180)),
        pool_timeout=int(PLATFORM_CONFIG.get("DB_POOL_TIMEOUT", 30)),
        connect_args={
            "connect_timeout": int(PLATFORM_CONFIG.get("PGCONNECT_TIMEOUT", 10)),
            "keepalives": 1,
            "keepalives_idle": 30,
            "keepalives_interval": 10,
            "keepalives_count": 5,
            "gssencmode": "disable",  # Fix GSSAPI/Kerberos authentication issue
        },
    )

def _get_engine(url: str) -> Engine:
    eng = _ENGINE_CACHE.get(url)
    if eng is None:
        eng = _build_engine(url)
        _ENGINE_CACHE[url] = eng
    return eng

# default/global engine for the base DSN

def _has_field_type_conflict(original: str, candidate: str) -> bool:
    """100% STRICT conflict detection - any semantic type difference is a conflict."""
    
    # Extract semantic field types
    orig_field_type = _extract_field_semantic_type(original)
    cand_field_type = _extract_field_semantic_type(candidate)
    
    # STRICT RULE: If both have identifiable field types, they MUST match exactly
    if orig_field_type and cand_field_type:
        return orig_field_type != cand_field_type
    
    # STRICT RULE: If one has a type and the other doesn't, assume potential conflict
    # This prevents matching typed fields with generic/unknown fields
    if (orig_field_type and not cand_field_type) or (not orig_field_type and cand_field_type):
        # Check token similarity - if very low, assume conflict
        token_sim = _tokens_similarity(original, candidate)
        return token_sim < 0.7  # High threshold for avoiding conflicts
    
    # If neither has a clear type, no conflict
    return False


def _extract_field_semantic_type(uid_text: str) -> str:
    """Extract semantic field type from UID using pattern recognition."""
    import re
    
    # Convert to lowercase for analysis
    text = uid_text.lower()
    
    # Authentication/Identity patterns - flexible matching with underscores
    if re.search(r'(password|pass|pwd|passphrase)', text):
        return 'password'
    if re.search(r'(user_?id|username|login|user_?name)', text):
        return 'identity'
    
    # Contact information patterns
    if re.search(r'(email|mail|e_?mail)', text):
        return 'email'
    if re.search(r'(phone|tel|telephone|mobile|cell)', text):
        return 'phone'
    
    # Address patterns
    if re.search(r'(address|street|addr|line)', text):
        return 'address'
    if re.search(r'(city|town|locality)', text):
        return 'city'
    if re.search(r'(state|province|region)', text):
        return 'state'
    if re.search(r'(zip|postal|postcode)', text):
        return 'postal'
    if re.search(r'(country|nation)', text):
        return 'country'
    
    # Name patterns
    if re.search(r'(first_?name|fname|given_?name)', text):
        return 'first_name'
    if re.search(r'(last_?name|lname|surname|family_?name)', text):
        return 'last_name'
    if re.search(r'(full_?name)', text) or (re.search(r'(name)', text) and not re.search(r'(first|last|user)', text)):
        return 'full_name'
    
    # Payment patterns
    if (re.search(r'(card|credit|debit|payment)', text) and re.search(r'(number|num)', text)):
        return 'card_number'
    if re.search(r'(cvv|cvc|security)', text) and re.search(r'(code)', text):
        return 'security_code'
    if re.search(r'(expir|exp)', text) and re.search(r'(date|month|year)', text):
        return 'expiry'
    if re.search(r'(billing)', text):
        return 'billing_info'
    if re.search(r'(shipping)', text):
        return 'shipping_info'
    
    # Action patterns
    if re.search(r'(click|button|btn)', text):
        return 'clickable'
    if re.search(r'(submit|confirm|save)', text):
        return 'submit_action'
    if re.search(r'(select|dropdown|choose)', text):
        return 'selection'
    
    # Return None if no clear semantic type identified
    return None



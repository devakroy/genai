# Normalization: lowercase, replace non-alnum with "_", collapse repeats, trim "_",
# strip trailing "_digits" (e.g., PDP id suffix)
_SEP_RE = re.compile(r"[^a-z0-9]+", re.IGNORECASE)
_TRAIL_ID_RE = re.compile(r"_(\d+)$")

def _normalize_uid(u: str) -> str:
    if not u:
        return ""
    u = _SEP_RE.sub("_", u.strip().lower())
    u = re.sub(r"_+", "_", u).strip("_")
    u = _TRAIL_ID_RE.sub("", u)
    return u

def _escape_like(s: str) -> str:
    """Escape %, _ and backslash for SQL LIKE."""
    return s.replace("\\", "\\\\").replace("%", r"\%").replace("_", r"\_")


def _with_retries(fn: Callable[[], Any], retries: int = 3, backoffs: Tuple[float, ...] = (0.5, 1.0, 2.0)):
    """
    Run a DB operation with bounded retries on transient OperationalError/DatabaseError.
    """
    attempt = 0
    while True:
        try:
            return fn()
        except (OperationalError, DatabaseError) as e:
            if attempt >= retries:
                raise
            time.sleep(backoffs[min(attempt, len(backoffs)-1)])
            attempt += 1


